"""Generate the sealed maze tasks.

    python3 tools/make_maze_tasks.py            # writes tasks/maze-*
    python3 tools/make_maze_tasks.py OUT_DIR    # writes them under OUT_DIR instead

Deterministic: re-running gives byte-identical files, so a task's hash changes only when this script or
src/swarm/maze.py's CLI does. Each task's workspace holds the `./maze` client and nothing else. The maze itself
is generated by the service at run time from the seed in task.toml and is never written to disk here.

  maze-branchy-shared    prim 40x25, one shared map: a swarm can split the branches
  maze-branchy-own       the same maze, every agent alone: the no-coordination baseline
  maze-corridor-shared   backtracker 40x25, no loops: long corridors, fewer branches to split
  maze-line-shared       serpentine 40x25 from the corner: one path, nothing to split (the negative control)
  maze-large-shared      prim 64x40: scaling
  maze-budget-shared     prim 40x25 with call_budget = one Ante's calls alone: coordination at equal cost
"""
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))

from swarm.maze import CLI_SOURCE, simulate, validate_params  # noqa: E402

BASE = {"cols": 40, "rows": 25, "seed": 2026, "generator": "prim", "loops": 0.05, "start": "center",
        "map": "shared", "step_limit": 4000, "call_budget": 0}

# step_limit on the large maze is above the default because one Ante alone needs more than 4000 calls there;
# without room the solo baseline would fail on the limit instead of measuring the maze.
TASKS = {
    "maze-branchy-shared": ({}, 1800),
    "maze-branchy-own": ({"map": "own"}, 1800),
    "maze-corridor-shared": ({"generator": "backtracker", "loops": 0.0}, 3600),
    "maze-line-shared": ({"generator": "serpentine", "loops": 0.0, "start": "corner"}, 3600),
    "maze-large-shared": ({"cols": 64, "rows": 40, "step_limit": 12000}, 7200),
    "maze-budget-shared": ({"call_budget": None}, 1800),   # filled in below from the solo run
}

INSTRUCTION = """You are inside a maze. Reach the exit.

You cannot see the maze. You explore it with one command, `./maze`, run from your working directory. Do not edit
any files; only run `./maze`. Every command prints one line of JSON.

  ./maze look           where you are, which sides are open, and which of those lead somewhere not yet explored
  ./maze move N|E|S|W   step through an open side; N is up (y - 1), E is right (x + 1)
  ./maze next-edge      shared map only: get a path to the nearest unexplored opening nobody else is heading for
  ./maze map            every cell explored so far and its open sides
  ./maze verdict        whether your run counts as a pass

`look` and `move` answer with `{"at":[x,y],"open":[...],"new":[...],"exit":false,"steps":n,"done":false}`.
`open` lists the sides you can walk through, `new` the open sides that lead into cells not yet explored, `exit` is
true when you are standing on the exit. Moving into a wall is refused and counts against you, so only move through
sides listed in `open`. Every call, refused ones too, counts toward a limit on how many calls you may make (in some
runs one limit is shared by every agent), and `done` becomes true when the run is over.

@MAP@

Stop when `exit` or `done` is true, or when a command answers with an error. Then say in one line what happened.
"""

MAP_SHARED = """The map is shared. Other agents are exploring this same maze at the same time, and `new` only lists
sides that nobody, you or them, has explored yet. When nothing near you is new, `./maze next-edge` returns a path
(a list of moves) to the nearest unexplored opening that nobody else has claimed, and claims it for you. Follow
that path with `move`. The run is over (`done`) as soon as any agent reaches the exit."""

MAP_OWN = """The map is yours alone: `new` only lists sides you have not explored yourself. Other agents may be in
their own copy of this maze, but you do not share anything with them. `./maze next-edge` is not available; when
nothing near you is new, walk back along your own steps to the last place that has an unexplored side."""

TEST_SH = """#!/bin/bash
set -euo pipefail
out=$(python3 ./maze verdict)
echo "$out"
python3 -c 'import json,sys; sys.exit(0 if json.loads(sys.argv[1]).get("passed") is True else 1)' "$out"
"""


def toml_value(value) -> str:
    if isinstance(value, str):
        return f'"{value}"'
    return repr(value)


def task_toml(task_id: str, params: dict, timeout: int) -> str:
    maze = "\n".join(f"{key} = {toml_value(params[key])}" for key in
                     ("cols", "rows", "seed", "generator", "loops", "start", "map", "step_limit", "call_budget"))
    return (f'[task]\nid = "{task_id}"\nallowed_changes = []\n\n[agent]\ntimeout_sec = {timeout}\n\n'
            f'[maze]\n{maze}\n\n[metadata]\ntags = ["maze"]\n')


def build(out: Path) -> None:
    solo = simulate({**BASE, "map": "own"}, 1)
    if solo["exit_tick"] is None:
        raise SystemExit("one Ante alone never reaches the exit on the budget task's maze")
    for task_id, (override, timeout) in TASKS.items():
        params = {**BASE, **override}
        if params["call_budget"] is None:
            params["call_budget"] = solo["calls"]
        params = validate_params(params)
        root = out / task_id
        if root.exists():
            shutil.rmtree(root)
        (root / "workspace").mkdir(parents=True)
        (root / "tests").mkdir()
        (root / "task.toml").write_text(task_toml(task_id, params, timeout))
        text = MAP_SHARED if params["map"] == "shared" else MAP_OWN
        (root / "instruction.md").write_text(INSTRUCTION.replace("@MAP@", text))
        cli = root / "workspace" / "maze"
        cli.write_text(CLI_SOURCE)
        cli.chmod(0o755)
        (root / "tests" / "test.sh").write_text(TEST_SH)
        (root / "tests" / "test.sh").chmod(0o755)


if __name__ == "__main__":
    build(Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "tasks")
