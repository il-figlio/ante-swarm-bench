"""Shared helpers for the budget-report checks.

tests/manifest.json is the ground truth (generated by
tools/gen_data.py): per-key/team/week aggregates, the over-cap list,
the top calls, and a sha256 of every input file. data/ and the JSON
configs are not restored before a check runs, so each check verifies
the input hashes before believing any output.
"""
import csv
import hashlib
import json
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MANIFEST = json.loads((ROOT / "tests" / "manifest.json").read_text())

EPS = 0.02                    # tolerance on a 2-decimal dollar figure
PCT_EPS = 0.51                # tolerates percent rounded to the integer

MONEY2_RE = re.compile(r"^[0-9]+\.[0-9]{2}$")
INT_RE = re.compile(r"^[0-9]+$")
# $-amounts of any precision, plus bare two-decimal amounts — but not
# percentages ("18.6%"), versions or mid-word digits.
MONEY_RE = re.compile(
    r"\$\s?([0-9][0-9,]*(?:\.[0-9]+)?)"
    r"|(?<![\w$])([0-9][0-9,]*\.[0-9]{2})(?![\w%.])")
PCT_RE = re.compile(r"([0-9]+(?:\.[0-9]+)?)\s?%")
HEADING_RE = re.compile(r"^##\s+(\S.*?)\s*$", re.M)


def sha256(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def tampered_inputs():
    """Repo-relative input files missing or whose sha256 differs from
    the manifest. Any tampering fails every check."""
    bad = []
    for rel, want in MANIFEST["input_hashes"].items():
        path = ROOT / rel
        if not path.is_file() or sha256(path) != want:
            bad.append(rel)
    return sorted(bad)


def run_report(*args):
    """`python3 report.py <args>` in the repo root -> CompletedProcess
    or None if report.py is missing."""
    if not (ROOT / "report.py").is_file():
        return None
    return subprocess.run(
        [sys.executable, "report.py", *args],
        cwd=ROOT, capture_output=True, text=True, timeout=120)


def csv_rows(path):
    with open(path, newline="") as f:
        return [row for row in csv.reader(f) if row]


def money_amounts(text):
    """Every dollar figure cited in `text`, as floats."""
    out = []
    for m in MONEY_RE.finditer(text):
        raw = (m.group(1) or m.group(2)).replace(",", "")
        out.append(float(raw))
    return out


def percents(text):
    """Every `N%` / `N.N%` figure cited in `text`."""
    return [float(m.group(1)) for m in PCT_RE.finditer(text)]


def _leaves(node, suffix):
    if isinstance(node, dict):
        for k, v in node.items():
            if (isinstance(v, (int, float)) and not isinstance(v, bool)
                    and k.endswith(suffix)):
                yield float(v)
            else:
                yield from _leaves(v, suffix)
    elif isinstance(node, list):
        for v in node:
            yield from _leaves(v, suffix)


def allowed_usd():
    """Every legitimate dollar figure — every *_usd leaf in the
    manifest (spends, caps, overages, headroom, rates, projections,
    per-call and per-day numbers)."""
    return sorted(set(_leaves(MANIFEST, "_usd")))


def allowed_pct():
    """Every legitimate percentage — every *_pct leaf (cap usage,
    shares, the week-over-week delta)."""
    return sorted(set(_leaves(MANIFEST, "_pct")))


def near(value, candidates, eps=EPS):
    return any(abs(value - c) <= eps for c in candidates)
