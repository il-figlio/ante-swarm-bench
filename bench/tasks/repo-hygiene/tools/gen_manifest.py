#!/usr/bin/env python3
"""Regenerate tests/manifest.json from the current tree.

The dead-function list is declared below; everything else (top-level
function inventories, AST/token fingerprints) is computed, so the
manifest always describes the tree it was generated from. Run it
against a pristine tree — the fingerprints feed check_h03's
"behaviour unchanged" comparison.
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from tests.hygiene import ast_hash, function_names, token_hash

DEAD = [
    ("tally/ledger.py", "normalize_header"),
    ("tally/ledger.py", "parse_legacy_amount"),
    ("tally/report.py", "render_csv"),
    ("tally/report.py", "bar"),
]


def main():
    files = sorted(p.relative_to(ROOT).as_posix()
                   for p in (ROOT / "tally").rglob("*.py"))
    manifest = {
        "note": "generated by tools/gen_manifest.py — do not edit",
        "dead_functions": [{"file": f, "name": n} for f, n in DEAD],
        "functions": {f: function_names(ROOT / f) for f in files},
        "ast_hashes": {f: ast_hash(ROOT / f) for f in files},
        "token_hashes": {f: token_hash(ROOT / f) for f in files},
    }
    out = ROOT / "tests" / "manifest.json"
    out.write_text(json.dumps(manifest, indent=1, sort_keys=True) + "\n")
    print("wrote %s" % out.relative_to(ROOT))


if __name__ == "__main__":
    sys.exit(main())
